export function romanizeKana(text: string): string {
  let result = '';
  let i = 0;
  while (i < text.length) {
    if (i + 1 < text.length && KANA_MAP[text.substring(i, i + 2)]) {
      result += KANA_MAP[text.substring(i, i + 2)];
      i += 2;
    } else if (KANA_MAP[text[i]]) {
      result += KANA_MAP[text[i]];
      i++;
    } else {
      result += text[i];
      i++;
    }
  }
  return result;
}

export function hasKoreanChars(text: string): boolean {
  return /[\uAC00-\uD7AF\u1100-\u11FF]/.test(text);
}

export function hasJapaneseChars(text: string): boolean {
  return /[\u3040-\u309F\u30A0-\u30FF\u4E00-\u9FAF]/.test(text);
}

export function romanizeText(text: string): string {
  if (!text) return '';
  if (hasKoreanChars(text)) {
    return romanizeKorean(text);
  }
  if (hasJapaneseChars(text)) {
    return romanizeKana(text);
  }
  return text;
}
